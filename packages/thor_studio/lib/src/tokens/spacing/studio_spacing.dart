/// The spacing scale (a 4 px grid): gaps, paddings and rhythm come from
/// here, never from a loose number.
abstract final class StudioSpacing {
  /// 4.
  static const double xxs = 4;

  /// 8.
  static const double xs = 8;

  /// 12.
  static const double sm = 12;

  /// 16.
  static const double md = 16;

  /// 24.
  static const double lg = 24;

  /// 32.
  static const double xl = 32;

  /// 48.
  static const double xxl = 48;

  /// 72: the gap between the big blocks of a page.
  static const double section = 72;
}
