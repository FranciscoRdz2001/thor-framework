/// The lite engine's bundle (`thor build` with `engine: lite`):
/// the runtime (`lib/lite/runtime.js`), the optional parts the app uses
/// (`lib/lite/parts/<part>.js`) sewn into it, and the app's states that
/// thor_builder translated from Dart, minified in one file.
///
/// The bundle ships at the engine's URL (`engine.dart.js`, fingerprinted
/// like the dart2js engine), so the page's HTML is the same with either
/// engine: the protocol of `data-t*` markers is the contract.
library;

