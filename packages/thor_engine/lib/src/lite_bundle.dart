/// The parts an app needs, in bundle order: those its states name
/// ([stateJs]'s `// thor-lite parts:` line) and those its engine features
/// ([engineEntry]) bring. With [pages] (a static site: every page known) a
/// feature's part ships only if a page has its markup; without them (a
/// server app) every part the features name ships, row states only if the
/// app's Dart [sources] build a `row.watch`.
List<String> litePartsFor({
  required String stateJs,
  required String engineEntry,
  List<String>? pages,
  String sources = '',
}) {
  final parts = <String>{
    ...?RegExp(
      r'^// thor-lite parts: (.*)$',
      multiLine: true,
    ).firstMatch(stateJs)?.group(1)!.split(' '),
  };
  for (final MapEntry(key: part, value: (feature, markup))
      in _featureParts.entries) {
    if (pages != null) {
      if (pages.any(markup.hasMatch)) parts.add(part);
    } else if (feature.hasMatch(engineEntry)) {
      if (switch (part) {
        'row_states' =>
          RegExp(r'\.(watch|selected)\s*\(').hasMatch(sources) &&
              RegExp(r'\bWatchItem\b|each:').hasMatch(sources),
        // Only an app with an `onPageChanged:` ships it (the feature's
        // other callbacks are not it).
        'page_view' => RegExp(r'\bonPageChanged\s*:').hasMatch(sources),
        // Only an app with a `VisibilityDetector`.
        'visibility' => RegExp(
          r'(?<![\w.])VisibilityDetector\s*\(',
        ).hasMatch(sources),
        // Only an app with `Shortcuts`/`Actions` or a `Focus(onKeyEvent:)`
        // (not `CallbackShortcuts`).
        'key_actions' => RegExp(
          r'(?<![\w.])(Shortcuts|Actions)\s*\(|\bonKeyEvent\s*:',
        ).hasMatch(sources),
        // Only an app with an `AnimatedSwitcher` (the other `Watch` builders
        // switch in place).
        'view_transition' => RegExp(
          r'\bAnimatedSwitcher\s*[<(]',
        ).hasMatch(sources),
        // The browser's own drag and drop only for an app that has a
        // `NativeDraggable`/`NativeDragTarget`; the pointer one not for an
        // app that has only those.
        'native_drag' => RegExp(
          r'(?<![\w.])NativeDrag(gable|Target)\b',
        ).hasMatch(sources),
        'drag_drop' =>
          !RegExp(r'(?<![\w.])NativeDrag(gable|Target)\b').hasMatch(sources) ||
              RegExp(
                r'(?<![\w.])(Draggable|LongPressDraggable|DragTarget)\b',
              ).hasMatch(sources),
        _ => true,
      }) {
        parts.add(part);
      }
    }
  }
  // Content that arrives after the page: a server app only (a static site
  // is complete when it is exported).
  if (pages == null &&
      RegExp(r'\b(FutureBuilder|LazyPiece)\s*[<(]').hasMatch(sources)) {
    parts.add('stream');
  }
  // Parts that need no engine feature: a tap on an element the markup
  // marks (a server app asks the sources, a static site its pages).
  for (final MapEntry(key: part, value: (code, markup))
      in _browserApiParts.entries) {
    if (pages != null ? pages.any(markup.hasMatch) : code.hasMatch(sources)) {
      parts.add(part);
    }
  }
  for (final part in parts.toList()) {
    parts.addAll(_needs[part] ?? const []);
  }
  for (final part in parts) {
    if (!liteParts.contains(part)) {
      throw ArgumentError.value(part, 'part', 'unknown thor-lite part');
    }
  }
  return [
    for (final p in liteParts)
      if (parts.contains(p)) p,
  ];
}

/// The bundle: [runtime] with [parts] (name → source, in bundle order) at
/// its `// @thor-lite-parts` line, inside its scope, then [stateJs],
/// minified unless [minify] is false.
String liteBundle({
  required String runtime,
  required Map<String, String> parts,
  required String stateJs,
  bool minify = true,
}) {
  const marker = '// @thor-lite-parts';
  if (!runtime.contains(marker)) {
    throw ArgumentError.value('runtime', 'runtime', 'has no $marker line');
  }
  final code = [for (final p in liteParts) ?parts[p]].join('\n');
  final engine = runtime.replaceFirst(marker, code);
  if (!minify) return '$engine\n$stateJs';
  // The runtime's and the parts' locals get short names (the states come
  // with theirs from thor_builder).
  return minifyJs('${renameLocals(engine)}\n$stateJs');
}

/// The `intl` part with the plural rules of [locales] only (the app's
/// languages: its `lib/l10n/*.arb`), their renamed spellings (`he`/`iw`,
/// `id`/`in`, `no`/`nb`, `fil`/`tl`) and `en` (the system locale when a
/// call names none). `Intl.pluralLogic` gives the same answer for every
/// locale of those languages: its fallbacks never leave a language or its
/// renamed one. Another language falls to `other`, so the generated
/// messages are the only callers it serves (a `ThorState` calling
/// `Intl.plural` with a locale of its own must list it in `lib/l10n`).
String trimIntlPart(String part, Iterable<String> locales) {
  const renamed = {
    'iw': 'he',
    'he': 'iw',
    'fil': 'tl',
    'tl': 'fil',
    'id': 'in',
    'in': 'id',
    'no': 'nb',
    'nb': 'no',
  };
  String language(String tag) => tag.split(RegExp('[-_]')).first.toLowerCase();
  final keep = <String>{'en'};
  for (final tag in locales) {
    final lang = language(tag);
    keep.add(lang);
    if (renamed[lang] case final other?) keep.add(other);
  }
  final lines = part.split('\n');
  final out = <String>[];
  final table = RegExp(r"^    '([^']+)': R\.(\w+),$");
  final rule = RegExp(r'^    (\w+): \(\) =>');
  // Which rule functions the kept table entries name ('default' always).
  final used = <String>{'default'};
  var inTable = false;
  for (final line in lines) {
    if (line == '  const rules = {') inTable = true;
    if (inTable && line == '  };') inTable = false;
    if (inTable) {
      final m = table.firstMatch(line);
      if (m != null && keep.contains(language(m.group(1)!))) {
        used.add(m.group(2)!);
      }
    }
  }
  var inRules = false;
  var skipping = false;
  inTable = false;
  for (final line in lines) {
    if (line == '  const R = {') {
      inRules = true;
      out.add(line);
      continue;
    }
    if (inRules && line == '  };') {
      inRules = false;
      skipping = false;
    }
    if (inRules) {
      final m = rule.firstMatch(line);
      if (m != null) skipping = !used.contains(m.group(1));
      if (!skipping) out.add(line);
      continue;
    }
    if (line == '  const rules = {') inTable = true;
    if (inTable && line == '  };') inTable = false;
    if (inTable) {
      final m = table.firstMatch(line);
      if (m != null && !keep.contains(language(m.group(1)!))) continue;
    }
    out.add(line);
  }
  return out.join('\n');
}
