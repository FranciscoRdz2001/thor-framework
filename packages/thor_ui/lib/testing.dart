/// Test helpers: render thor components to HTML in a VM test.
///
/// The HTTP test client (`handler.client()`, `hasStatus`, `redirectsTo`)
/// lives in `package:thor_test/thor_test.dart` (a dev dependency), which
/// exports these helpers too.
///
/// ```dart
/// void main() {
///   setUpAll(initializeThorTests);
///   test('Row is a flexbox', () async {
///     final html = await renderHtml(const Row(children: [Text('a')]));
///     expect(html, contains('display: flex'));
///   });
/// }
/// ```
library;

import 'dart:convert';
import 'dart:io';

import 'server.dart' show Document, initializeThor;
import 'src/core/core.dart';
import 'src/core/framework.dart' show PageBuild, WidgetTrace;
import 'src/core/render.dart' as render;
import 'src/foundation/style_registry.dart' as registry;

export 'src/core/framework.dart' show WidgetTrace;
export 'src/foundation/clock.dart' show withThorNow;

/// Initializes rendering for tests. With [compactHtml] (the default) the
/// output has no pretty-printing whitespace, exactly like a release build.
void initializeThorTests({bool compactHtml = true}) {
  initializeThor();
  render.compactHtml = compactHtml;
}

/// Renders [component] alone (no document) and returns its HTML.
Future<String> renderHtml(Widget component) async {
  final result = await render.renderPage(component, standalone: true);
  return utf8.decode(result.body).trim();
}

/// [renderHtml] with the widgets that built each element recorded: every
/// element carries `data-thor-w` with indexes into `widgets`.
/// What `find.byType` and `find.byKey` of `thor_test` read; the render
/// caches are off while it runs, so every widget builds. It must not overlap
/// another render in the same isolate (the trace is global).
Future<({String html, List<({Type type, Key? key})> widgets})> renderHtmlTraced(
  Widget component,
) async {
  final trace = WidgetTrace();
  final caches = registry.renderCachesEnabled;
  registry.renderCachesEnabled = false;
  PageBuild.trace = trace;
  try {
    final result = await render.renderPage(component, standalone: true);
    return (html: utf8.decode(result.body).trim(), widgets: trace.widgets);
  } finally {
    PageBuild.trace = null;
    registry.renderCachesEnabled = caches;
  }
}

/// Renders a full page (`<html>`, `<head>` with the generated stylesheet,
/// `<body>`) whose body is [body].
Future<String> renderDocument(Widget body) async {
  final result = await render.renderPage(Document(body: body));
  return utf8.decode(result.body);
}

/// The `<body>…</body>` part of a rendered page.
String bodyOfPage(String html) => html.substring(html.indexOf('<body'));

/// The `<head>` part of a rendered page (styles, sprite, state).
String headOfPage(String html) => html.substring(0, html.indexOf('</head>'));

/// Whether the render-time caches are on (the default): the memo of each
/// element's styles and the fragments kept by `Cached`. Off, every element
/// computes its styles and every `Cached` builds its child: the reference
/// a differential test compares the cached output against, byte for byte.
bool get renderCachesEnabled => registry.renderCachesEnabled;
set renderCachesEnabled(bool enabled) => registry.renderCachesEnabled = enabled;

/// Runs [script] of the app (a path like `test/fixtures/pages.dart`) with
/// `dart run`, the way thor runs the app: with its states and its pages'
/// action methods registered first. For a test that renders in
/// another process (a compile-time define, a fresh isolate). [dartArgs] go
/// before the script (`-Dthor.release=true`), [args] after it. [appDir] is
/// the app (default: the current folder, where `thor test` runs).
Future<ProcessResult> runAppScript(
  String script, {
  List<String> args = const [],
  List<String> dartArgs = const [],
  Map<String, String>? environment,
  String? appDir,
}) async {
  final dir = Directory(appDir ?? Directory.current.path).absolute.path;
  final parts = script.split('/')..removeWhere((s) => s.isEmpty || s == '.');
  final wrapper = File('$dir/.dart_tool/thor/run/${parts.join('/')}');
  wrapper.parent.createSync(recursive: true);
  // From .dart_tool/thor/run/<script folders>/ back up to the app.
  final up = '../' * (parts.length - 1 + 3);
  final states = File('$dir/.dart_tool/thor/states.dart').existsSync();
  final actions = File('$dir/.dart_tool/thor/actions.dart').existsSync();
  final thor = '../' * (parts.length - 1 + 1);
  wrapper.writeAsStringSync('''
// GENERATED BY thor (runAppScript) - DO NOT MODIFY.
// ignore_for_file: type=lint
${states || actions ? "import 'package:thor_server/thor_server.dart' show ThorServer;" : ''}
import '$up${parts.join('/')}' as app;
${states ? "import '${thor}states.dart';" : ''}
${actions ? "import '${thor}actions.dart';" : ''}

Future<void> main(List<String> args) async {
  ${states ? 'ThorServer.setUpIsolates(registerThorStates);' : ''}
  ${actions ? 'ThorServer.setUpIsolates(registerThorActions);' : ''}
  final Function run = app.main;
  await (run is Function(List<String>) ? run(args) : (run as dynamic)());
}
''');
  return Process.run(
    Platform.resolvedExecutable,
    ['run', ...dartArgs, wrapper.path, ...args],
    workingDirectory: dir,
    environment: environment,
  );
}
