// Writes the lite engine's `intl` part (packages/thor_engine/lib/lite/parts/
// intl.js): package:intl's Intl.canonicalizedLocale and Intl.pluralLogic,
// with its plural rules translated rule for rule from the intl version the
// workspace resolves (lib/src/plural_rules.dart).
//
//   dart run tool/gen_lite_intl.dart
//
// Run it again when intl changes version; thor_builder's lite_intl_test
// compares the part with package:intl compiled by dart2js.
import 'dart:convert';
import 'dart:io';

import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/ast.dart';
import 'package:analyzer/dart/ast/token.dart';

void main() {
  final config =
      jsonDecode(File('.dart_tool/package_config.json').readAsStringSync())
          as Map<String, Object?>;
  final intl = (config['packages']! as List<Object?>)
      .cast<Map<String, Object?>>()
      .firstWhere((p) => p['name'] == 'intl');
  final root = Uri.parse(intl['rootUri']! as String).toFilePath();
  final version = RegExp(r'intl-([\d.]+)').firstMatch(root)?.group(1) ?? '?';
  final source = File('$root/lib/src/plural_rules.dart').readAsStringSync();
  final unit = parseString(content: source).unit;

  final rules = <String>[];
  final table = <String>[];
  for (final d in unit.declarations) {
    if (d is FunctionDeclaration && d.name.lexeme.endsWith('_rule')) {
      final name = d.name.lexeme.substring(1, d.name.lexeme.length - 5);
      rules.add('    $name: ${_function(d.functionExpression.body)},');
    }
    if (d is TopLevelVariableDeclaration &&
        d.variables.variables.single.name.lexeme == 'pluralRules') {
      final map = d.variables.variables.single.initializer! as SetOrMapLiteral;
      for (final e in map.elements.cast<MapLiteralEntry>()) {
        final key = (e.key as SimpleStringLiteral).value;
        final fn = (e.value as SimpleIdentifier).name;
        table.add("    '$key': R.${fn.substring(1, fn.length - 5)},");
      }
    }
  }
  if (rules.isEmpty || table.isEmpty) {
    stderr.writeln('plural_rules.dart changed shape: no rules found.');
    exit(1);
  }

  final out = File('packages/thor_engine/lib/lite/parts/intl.js');
  out.writeAsStringSync('''
// thor-lite part "intl": Intl.canonicalizedLocale and Intl.pluralLogic as
// package:intl $version runs them on the web (its plural rules, rule for
// rule; the fallbacks of verifiedLocale; the system locale en_US).
// GENERATED by tool/gen_lite_intl.dart — do not edit.
((T) => {
  T.intl = (() => {
  let n = 0, i = 0, v = 0, f = 0, t = 0, p = null;
  // Dart's % on these ints (never negative).
  const M = (a, b) => { const r = a % b; return r < 0 ? r + Math.abs(b) : r; };
  const round = (x) => (x < 0 ? -Math.round(-x) : Math.round(x));
  const R = {
${rules.join('\n')}
  };
  const rules = {
${table.join('\n')}
  };
  const decimals = (x) => {
    const s = p == null ? String(x) : x.toFixed(p);
    const at = s.indexOf('.');
    return at === -1 ? 0 : s.length - at - 1;
  };
  const start = (howMany, precision) => {
    n = howMany;
    p = precision;
    i = round(n);
    v = p ?? Math.min(decimals(n), 3);
    const base = 10 ** v;
    f = M(Math.floor(n * base), base);
    let ff = f;
    if (ff === 0) {
      t = 0;
    } else {
      while (ff % 10 === 0) ff = Math.floor(ff / 10);
      t = ff;
    }
  };
  const sep = (l) =>
    l.length < 3 ? -1 : l[2] === '-' || l[2] === '_' ? 2 : l.length < 4 ? -1 : l[3] === '-' || l[3] === '_' ? 3 : -1;
  const canon = (l) => {
    if (l == null) return 'en_US';
    if (l === 'C') return 'en_ISO';
    if (l.length < 5) return l;
    const at = sep(l);
    if (at === -1) return l;
    let region = l.substring(at + 1);
    if (region.length <= 3) region = region.toUpperCase();
    return l.substring(0, at) + '_' + region;
  };
  const languageOnly = (l) => {
    if (l === 'invalid') return 'in';
    if (l.length < 2) return l;
    const at = sep(l);
    if (at === -1) return l.length < 4 ? l.toLowerCase() : l;
    return l.substring(0, at).toLowerCase();
  };
  const languageRegionOnly = (l) => {
    if (l.length < 10) return l;
    let at = sep(l);
    if (at === -1) return l;
    const language = l.substring(0, at);
    const subtags = l.substring(at + 1);
    at = subtags.length < 5 ? -1 : subtags[4] === '-' || subtags[4] === '_' ? 4 : -1;
    let region = subtags.substring(at + 1);
    if (region.length <= 3) region = region.toUpperCase();
    return language + '_' + region;
  };
  const renamed = { iw: 'he', he: 'iw', fil: 'tl', tl: 'fil', id: 'in', in: 'id', no: 'nb', nb: 'no' };
  const deprecated = (l) => (Object.hasOwn(renamed, l) ? renamed[l] : l);
  const has = (l) => Object.hasOwn(rules, l);
  const verified = (l) => {
    if (l == null) l = 'en_US';
    if (has(l)) return l;
    for (const option of [
      canon,
      languageRegionOnly,
      languageOnly,
      deprecated,
      (x) => deprecated(languageOnly(x)),
      (x) => deprecated(canon(x)),
      () => 'fallback',
    ]) {
      const x = option(l);
      if (has(x)) return x;
    }
    return 'default';
  };
  return {
    canon,
    plural(howMany, zero, one, two, few, many, other, locale, precision, explicit = true) {
      if (!Number.isFinite(howMany)) throw new Error('Unsupported operation: Infinity or NaN toInt');
      const truncated = Math.trunc(howMany);
      if (precision == null && truncated === howMany) howMany = truncated;
      if (explicit && (precision == null || precision === 0)) {
        if (howMany === 0 && zero != null) return zero;
        if (howMany === 1 && one != null) return one;
        if (howMany === 2 && two != null) return two;
      }
      start(howMany, precision);
      switch (rules[verified(locale)]()) {
        case 'zero': return zero ?? other;
        case 'one': return one ?? other;
        case 'two': return two ?? few ?? other;
        case 'few': return few ?? other;
        case 'many': return many ?? other;
        default: return other;
      }
    },
  };
  })();
})(thor);
''');
  stdout.writeln('${out.path}: ${rules.length} rules, ${table.length} locales');
}

String _function(FunctionBody body) {
  if (body is ExpressionFunctionBody) return '() => ${_expr(body.expression)}';
  final block = (body as BlockFunctionBody).block;
  final lines = <String>[];
  for (final s in block.statements) {
    switch (s) {
      case IfStatement(
        thenStatement: Block(statements: [ReturnStatement(:final expression?)]),
        elseStatement: null,
      ):
        lines.add('if (${_expr(s.expression)}) return ${_expr(expression)};');
      case ReturnStatement(:final expression?):
        lines.add('return ${_expr(expression)};');
      default:
        throw UnsupportedError('Statement in a plural rule: $s');
    }
  }
  return '() => {\n${lines.map((l) => '      $l').join('\n')}\n    }';
}

const _vars = {'_n': 'n', '_i': 'i', '_v': 'v', '_f': 'f', '_t': 't'};
const _cases = {'ZERO', 'ONE', 'TWO', 'FEW', 'MANY', 'OTHER'};

String _expr(Expression e) {
  switch (e) {
    case ParenthesizedExpression():
      return '(${_expr(e.expression)})';
    case IntegerLiteral():
      return '${e.value}';
    case SimpleIdentifier(:final name) when _vars.containsKey(name):
      return _vars[name]!;
    case SimpleIdentifier(:final name) when _cases.contains(name):
      return "'${name.toLowerCase()}'";
    case PrefixExpression(operator: Token(lexeme: '!')):
      return '!${_expr(e.operand)}';
    case BinaryExpression():
      final op = e.operator.lexeme;
      final l = _expr(e.leftOperand), r = _expr(e.rightOperand);
      return switch (op) {
        '%' => 'M($l, $r)',
        '==' => '$l === $r',
        '!=' => '$l !== $r',
        '&&' || '||' || '<' || '<=' || '>' || '>=' => '$l $op $r',
        _ => throw UnsupportedError('Operator $op in a plural rule'),
      };
    // [3, 4, 5].contains(x)
    case MethodInvocation(
      target: ListLiteral(:final elements),
      methodName: SimpleIdentifier(name: 'contains'),
    ):
      final x = _expr(e.argumentList.arguments.single);
      return '[${elements.map((x) => _expr(x as Expression)).join(', ')}].includes($x)';
    // List.generate(k, (i) => i + s).contains(x): s ≤ x < s + k, integers.
    case MethodInvocation(
      target: MethodInvocation(
        target: SimpleIdentifier(name: 'List'),
        methodName: SimpleIdentifier(name: 'generate'),
        argumentList: ArgumentList(
          arguments: [
            IntegerLiteral(value: final k?),
            FunctionExpression(
              body: ExpressionFunctionBody(
                expression: BinaryExpression(
                  operator: Token(lexeme: '+'),
                  rightOperand: IntegerLiteral(value: final s?),
                ),
              ),
            ),
          ],
        ),
      ),
      methodName: SimpleIdentifier(name: 'contains'),
    ):
      final x = _expr(e.argumentList.arguments.single);
      return '(Number.isInteger($x) && $x >= $s && $x < ${s + k})';
    default:
      throw UnsupportedError('Expression in a plural rule: $e');
  }
}
